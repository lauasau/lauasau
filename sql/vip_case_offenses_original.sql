USE INFORMRMSREPORTS;

SELECT DISTINCT
    TT.CASENUMBER,
    TT.DATEREPORTED,
    TT.VIOLATIONCODEREFERENCE_DESCRIPTION,
    VIP.FULLNAME,
    VIP.DATEOFBIRTH
FROM
    (SELECT
        R.CASENUMBER,
        O.VIOLATIONCODEREFERENCE_DESCRIPTION,
        E.DATEREPORTED
     FROM REPORTING.REPORT R
        INNER JOIN REPORTING.OFFENSE O ON R.ID = O.RECORD_ID
        LEFT JOIN REPORTING.EVENT E ON R.ID = E.RECORD_ID
     WHERE E.DATEREPORTED IS NOT NULL
       AND E.DATEREPORTED >= DATEADD(YEAR, -5, GETDATE())   -- ONLY CASES REPORTED IN THE PAST 5 YEARS
    ) AS TT
INNER JOIN
    (SELECT DISTINCT
        R.CASENUMBER,
        R.CREATEDON,
        CONCAT(P.LASTNAME, ',', P.FIRSTNAME) AS FULLNAME,   -- NO SPACE AFTER COMMA
        P.RACE_CODE,
        P.SEX_CODE,
        P.DATEOFBIRTH,
        P.INVOLVEMENTTYPE_CODE
     FROM REPORTING.REPORT R
        INNER JOIN REPORTING.PERSON P ON R.ID = P.RECORD_ID
     WHERE
        (P.LASTNAME = 'DOE' AND P.FIRSTNAME = 'JOHN' AND P.DATEOFBIRTH = '07/10/1998')
     OR (P.LASTNAME = 'DOE' AND P.FIRSTNAME = 'JANE' AND P.DATEOFBIRTH = '06/17/1999')
    ) AS VIP
ON TT.CASENUMBER = VIP.CASENUMBER;
