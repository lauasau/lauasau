USE INFORMRMSREPORTS;

-- Which description goes with each involvement type code, and how often each pair is used.
SELECT
    P.INVOLVEMENTTYPE_CODE,
    P.INVOLVEMENTTYPE_DESCRIPTION,
    COUNT(*) AS TIMES_USED
FROM REPORTING.PERSON P
WHERE P.INVOLVEMENTTYPE_CODE IN ('01', '02', '03', '04', '05', '06')
GROUP BY P.INVOLVEMENTTYPE_CODE, P.INVOLVEMENTTYPE_DESCRIPTION
ORDER BY P.INVOLVEMENTTYPE_CODE, TIMES_USED DESC;
